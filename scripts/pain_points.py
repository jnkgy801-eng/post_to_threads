# 商品名に仕様ワードが見つからなかったときの「選び方の悩み」。具体的な悩みを商品に結びつけられないので、
# 解決策側は「レビューを目安に」という事実ベースの文になる(schedule_to_buffer.py の PS_SOLUTIONS_REVIEW)。
CHOICE_PAIN_POINTS: tuple[PainPoint, ...] = (
    PainPoint("種類が多すぎて、どれを選べばいいか迷う…", ()),
    PainPoint("失敗したくなくて、なかなか決めきれない…", ()),
    PainPoint("口コミを見比べているうちに、時間が過ぎてしまう…", ()),
)


@lru_cache(maxsize=None)
def _regex(pattern: str) -> re.Pattern[str]:
    return re.compile(pattern, re.IGNORECASE)


def _squash(text: str) -> str:
    """全角英数(ＳＰＦ５０)などの表記ゆれを吸収し、空白を除く。"""
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", text))


def find_feature(point: PainPoint, text: str, keyword: str | None = None) -> str | None:
    """
    商品名+キャッチコピーに、悩みに応える仕様ワードが含まれていれば、その表記を返す(先頭の特徴ほど優先)。
    検索キーワード自体に含まれる語(例: 布団乾燥機の「布団」)は全商品に含まれ、根拠にならないので採用しない。
    """
    normalized = unicodedata.normalize("NFKC", text)
    trivial = _squash(keyword or "")
    for pattern in point.features:
        m = _regex(pattern).search(normalized)
        if not m:
            continue
        found = _squash(m.group(0))
        if trivial and found in trivial:
            continue
        return found
    return None


def has_pain_match(keyword: str | None, text: str) -> bool:
    """辞書にあるキーワードで、商品が1つでも悩みに応える仕様ワードを持つか(汎用の悩みは判定が緩いので対象外)。"""
    points = PAIN_POINTS.get(keyword or "")
    return bool(points) and any(find_feature(p, text, keyword) for p in points)


def pick_pain_point(keyword: str | None, text: str) -> tuple[PainPoint, str | None]:
    """
    商品に合う悩みを選ぶ。仕様ワードが一致する悩みがあればその中からランダムに選ぶ。
    1つも一致しなければ「選び方の悩み」にする(具体的な悩みを、根拠なく商品に結びつけない)。
    戻り値は (悩み, 一致した仕様ワード or None)。
    """
    points = PAIN_POINTS.get(keyword or "", GENERIC_PAIN_POINTS)
    matched = [(p, f) for p in points if (f := find_feature(p, text, keyword))]
    if matched:
        return random.choice(matched)
    return random.choice(CHOICE_PAIN_POINTS), None


def render_problem(point: PainPoint, name: str) -> str:
    # str.format だと悩み文に波括弧が入ったときに壊れるため、単純置換にする
    return point.problem.replace("{n}", name)
